project_fixture <- function() {
  home <- tempfile("funmel_relocate_");dir.create(home)
  p <- structure(list(project_dir="/old/project",image_root="/external/photos",
    metadata_file="/old/project/plate_metadata.csv",qc_dir="/old/project/qc",
    result_file="/old/project/image_analysis.rds",reviewed_file="/old/project/reviewed_analysis.rds"),class="funmel_project")
  d <- example_experiment(seed=42)
  batch <- list(colonies=d$colonies,plates=d$metadata,failed=data.frame(file=character(),error=character()))
  saveRDS(p,file.path(home,"project.rds"));saveRDS(batch,file.path(home,"image_analysis.rds"))
  utils::write.csv(d$metadata,file.path(home,"plate_metadata.csv"),row.names=FALSE)
  list(home=home,p=p,batch=batch)
}
test_that("moved complete projects reconnect paths and preserve measurements", {
  f <- project_fixture();on.exit(unlink(f$home,recursive=TRUE))
  p <- load_experiment(f$home)
  expect_identical(p$project_dir,normalizePath(f$home))
  expect_identical(p$image_root,"/external/photos")
  expect_true(file.exists(p$metadata_file))
  expect_equal(read_experiment(p)$colonies,f$batch$colonies)
  expect_equal(read_experiment(p$result_file)$colonies,f$batch$colonies)
  expect_equal(load_experiment(p$result_file),p)
  expect_s3_class(suppressWarnings(plot_treatment_comparison(p)),"ggplot")
  x <- suppressWarnings(finish_experiment(p))
  expect_true(file.exists(p$reviewed_file))
  expect_equal(x$colonies$MI_mean,f$batch$colonies$MI_mean)
  expect_equal(read_experiment(p,finalized=TRUE)$colonies,x$colonies)
  unlink(p$result_file)
  expect_equal(read_experiment(p)$colonies,x$colonies)
})
test_that("missing and invalid saved inputs fail with actionable messages", {
  expect_error(load_experiment("/does/not/exist"),"Project path does not exist")
  expect_error(load_experiment(character()),"current project folder")
  f <- project_fixture();on.exit(unlink(f$home,recursive=TRUE))
  p <- load_experiment(f$home)
  expect_error(read_experiment(p,finalized=TRUE),"finish_experiment")
  unlink(p$result_file)
  expect_error(read_experiment(p),"Run run_experiment")
  bad <- file.path(f$home,"wrong.rds");saveRDS(1,bad)
  expect_error(load_experiment(bad),"neither a FunMel project")
})
test_that("stale object can reconnect via a selected sibling result without guessing another project", {
  f <- project_fixture();on.exit(unlink(f$home,recursive=TRUE))
  p <- f$p;p$result_file <- file.path(f$home,"image_analysis.rds")
  expect_equal(read_experiment(p)$colonies,f$batch$colonies)
  expect_message(FunMel:::as_funmel_project(p),"Reconnected moved")
  p$result_file <- file.path(f$home,"reviewed_analysis.rds")
  saveRDS(f$batch,p$result_file)
  expect_true(file.exists(FunMel:::as_funmel_project(p)$metadata_file))
})
test_that("all exports have function calls in the catalog", {
  f <- system.file("examples","06_all_functions.R",package="FunMel")
  src <- paste(readLines(f),collapse="\n")
  for(nm in getNamespaceExports("FunMel")) expect_match(src,paste0("\\b",nm,"\\s*\\("))
})
test_that("internal image roots move with the project and metadata is never guessed", {
  f <- project_fixture();on.exit(unlink(f$home,recursive=TRUE))
  p <- f$p;p$image_root <- "/old/project/photos"
  saveRDS(p,file.path(f$home,"project.rds"))
  moved <- load_experiment(file.path(f$home,"project.rds"))
  expect_equal(moved$image_root,file.path(normalizePath(f$home),"photos"))
  unlink(moved$metadata_file)
  expect_error(finish_experiment(moved),"metadata CSV is missing")
  expect_false(file.exists(moved$metadata_file))
})
