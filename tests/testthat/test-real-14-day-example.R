test_that("the bundled real-data walkthrough has complete pending-review metadata", {
  root <- system.file("extdata", "14-days", package="FunMel")
  expect_true(nzchar(root))
  m <- read.csv(file.path(root,"plate_metadata.csv"),check.names=FALSE)
  files <- list.files(root,recursive=TRUE,pattern="\\.JPG$",full.names=TRUE)
  expect_equal(length(files),8L)
  all_photos <- list.files(system.file("extdata",package="FunMel"),recursive=TRUE,pattern="\\.(jpg|jpeg)$",ignore.case=TRUE)
  expect_length(all_photos,8L)
  expect_equal(nrow(m),8L)
  expect_true(all(file.exists(file.path(root,m$relative_file))))
  expect_silent(validate_metadata(m,files))
  expect_equal(length(unique(m$set_id)),2L)
  expect_true(all(table(m$set_id,m$treatment=="control")==matrix(rep(c(3L,1L),each=2L),ncol=2)))
  expect_false("metadata_confirmed" %in% names(m));expect_false(any(m$qc_pass))
  expect_equal(unique(m$day),14L)
  expect_true(all(is.na(m$source_metadata_issue) | !nzchar(m$source_metadata_issue)))
  expect_true(all(c("notes","fungus","qc_pass","relative_file") %in% names(m)))
})
